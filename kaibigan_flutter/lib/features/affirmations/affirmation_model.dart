class AffirmationCategory {
  final String id;
  final String title;
  final String subtitle;
  final List<String> affirmations;
  final String filipinoTitle;
  final String filipinoSubtitle;
  final List<String> filipinoAffirmations;

  const AffirmationCategory({
    required this.id,
    required this.title,
    required this.subtitle,
    required this.affirmations,
    required this.filipinoTitle,
    required this.filipinoSubtitle,
    required this.filipinoAffirmations,
  });

  String titleFor(String language) =>
      language.toLowerCase() == 'filipino' ? filipinoTitle : title;

  String subtitleFor(String language) =>
      language.toLowerCase() == 'filipino' ? filipinoSubtitle : subtitle;

  List<String> affirmationsFor(String language) =>
      language.toLowerCase() == 'filipino'
          ? filipinoAffirmations
          : affirmations;
}

